import { createRequire } from 'module'; const { chromium } = createRequire(import.meta.url)('playwright');
import http from 'http'; import fs from 'fs';
const root = new URL('..', import.meta.url).pathname;
const srv = http.createServer((q, r) => { r.writeHead(200, { 'content-type': 'text/html' }); r.end(fs.readFileSync(root + 'index.html')); }).listen(0);
const b = await chromium.launch({ args: ['--enable-unsafe-webgpu', '--enable-features=Vulkan'] });
const p = await b.newPage({ viewport: { width: 640, height: 360 } });
p.on('console', m => console.log('console:', m.type(), m.text().slice(0, 1500)));
p.on('pageerror', e => console.log('pageerror:', e.message.slice(0, 1500), e.stack?.slice(0,500)));
await p.goto(`http://localhost:${srv.address().port}/?dbg&shot=0&w=640&h=360`);
await p.waitForTimeout(+process.argv[2] || 20000);
console.log(await p.evaluate(() => [window.__ready, document.body.innerText]));
await b.close(); srv.close();
